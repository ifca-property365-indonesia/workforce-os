import type { AutonomyLevel, ExecutionMode, ToolPermission } from "@wfos/shared";

export interface RoleTemplate {
  key: string;
  role: string;
  avatar: string;
  defaultName: string;
  /** one line of expertise (employees.specialty): how a head or code lead picks this person */
  specialty: string;
  /** the same in Indonesian (used when the workspace language is Indonesian) */
  specialtyId: string;
  tagline: string;
  persona: string;
  instructions: string;
  suggestedTools: ToolPermission[];
  autonomyLevel: AutonomyLevel;
  exampleTasks: string[];
  /** default model; heads and code leads reason more, members execute */
  model?: string;
  /** default execution mode; switching to workspace still needs Owner/Admin + 2FA confirmation */
  executionMode?: ExecutionMode;
  /** hosts the Workspace-mode sandbox may reach (package registries) */
  egressDomains?: string[];
}

